package com.hitomatito.hardwire.data.command

enum class DeviceCommand(val command: String) {
    GETPROP("getprop"),
    CPU_INFO("cat /proc/cpuinfo"),
    MEM_INFO("cat /proc/meminfo"),
    BATTERY("dumpsys battery"),
    DISPLAY_SIZE("wm size"),
    DISPLAY_DENSITY("wm density"),
    DISPLAY_INFO("dumpsys display"),
    CAMERAS("dumpsys media.camera"),
    SENSORS("dumpsys sensorservice"),
    DISK("df"),
    KERNEL_VERSION("cat /proc/version"),
    NETWORK("ip addr"),
    WIFI_INTERFACE("getprop wifi.interface"),
    IMEI("service call iphonesubinfo 1 s16 com.android.shell"),
    IMEI_SLOT2("service call iphonesubinfo 2 s16 com.android.shell"),
    IMEI_SLOT2_A("service call iphonesubinfo 4 i32 0 s16 com.android.shell"),
    IMEI_SLOT2_B("service call iphonesubinfo 4 i32 1 s16 com.android.shell"),
    IMEI_ALT("dumpsys iphonesubinfo"),
    IMEI_V2_0("cmd phone get-imei 0"),
    IMEI_V2_1("cmd phone get-imei 1"),
    PARTITIONS("cat /proc/partitions"),
    SOC_MODEL("getprop ro.soc.model"),
    SOC_MANUFACTURER("getprop ro.soc.manufacturer"),
    SOC_CHIPNAME("getprop ro.hardware.chipname"),
    SOC_PLATFORM("getprop ro.board.platform"),
    SOC_VENDOR_MODEL("getprop ro.vendor.soc.model"),
    PHONE("getprop gsm.version.baseband"),
    DEVICE_MARKET_NAME("getprop ro.product.marketname"),
    SURFACE_FLINGER("dumpsys SurfaceFlinger"),
    SURFACE_FLINGER_LATENCY("dumpsys SurfaceFlinger --latency"),
    SOC0_FAMILY("cat /sys/devices/soc0/family"),
    SOC0_MACHINE("cat /sys/devices/soc0/machine")
}
